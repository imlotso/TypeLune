import { readFile } from 'node:fs/promises';
import { expect, test } from './fixtures';
import type { Page } from '@playwright/test';

async function practicePrivate(page: Page, title: string) {
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '新建文章' }).click();
  await page.getByRole('dialog').waitFor();
  const guestNotice = page.getByRole('dialog', { name: '游客文章仅保存在本机' });
  if (await guestNotice.isVisible()) await guestNotice.getByRole('button', { name: '我已知晓，继续创建' }).click();
  const editor = page.getByRole('dialog', { name: '新建文章' });
  await editor.getByLabel('标题').fill(title);
  await editor.getByLabel('正文').fill('山海');
  await editor.getByRole('button', { name: '保存' }).click();
  await page.getByRole('button', { name: `练习《${title}》` }).click();
  await page.getByRole('textbox', { name: '当前行输入' }).fill('山海');
  await page.getByRole('dialog', { name: '练习成绩' }).getByRole('button', { name: '关闭' }).click();
}

test('deletes selected guest-only records while offline without affecting the private article', async ({ page, context }) => {
  await page.goto('/');
  await practicePrivate(page, '山');
  await practicePrivate(page, '海');
  await page.getByRole('button', { name: '我的记录' }).click();
  await page.getByRole('checkbox', { name: '选择《山》' }).check();
  await page.getByRole('checkbox', { name: '选择《海》' }).check();
  await context.setOffline(true);
  await page.getByRole('button', { name: '删除所选（2）' }).click();
  const confirm = page.getByRole('dialog', { name: '删除记录' });
  await expect(confirm.getByText(/撤回关联的公开成绩/)).toBeVisible();
  await confirm.getByRole('button', { name: '删除' }).click();
  await expect(confirm).toBeHidden();
  await expect(page.getByText('暂无记录')).toBeVisible();
  await context.setOffline(false);
  await page.reload();
  await page.getByRole('button', { name: '我的记录' }).click();
  await expect(page.getByText('暂无记录')).toBeVisible();
  await page.getByRole('button', { name: '文章库' }).click();
  await expect(page.getByRole('button', { name: '练习《山》' })).toBeVisible();
});

