import { ensureAdmin, expect, test } from './fixtures';

test('shows submission and review decisions consistently in results and history', async ({ page, browser, baseURL, clientIp }) => {
  const username = 'score_reader'; const email = `${username}@example.test`;
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { email, username, password: 'score-password-123', code } })).ok()).toBe(true);
  await page.goto('/');
  await page.getByRole('textbox', { name: '当前行输入' }).fill('我');
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: '结束练习', exact: true }).click();
  await page.getByRole('dialog', { name: '结束本次练习？' }).getByRole('button', { name: '结束并查看成绩' }).click();
  let result = page.getByRole('dialog', { name: '练习成绩' });
  await expect(result.getByText('尚未提交。')).toBeVisible();
  await result.getByRole('button', { name: '提交到排行榜' }).click();
  await expect(result.getByText('已提交，待复核。')).toBeVisible();
  const adminContext = await browser.newContext({ baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  await ensureAdmin(adminContext.request);
  const admin = await adminContext.newPage(); await admin.goto('/admin');
  await admin.getByRole('button', { name: '成绩', exact: true }).click();
  const row = admin.locator('li').filter({ hasText: username });
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: '拒绝', exact: true }).click();
  const review = admin.getByRole('dialog', { name: '拒绝成绩' });
  await review.getByLabel('原因', { exact: true }).fill('内部审核细节');
  await review.getByLabel('用户可见说明').fill('请重新练习后提交');
  await review.getByRole('button', { name: '确认拒绝' }).click();
  await expect(review).toHaveCount(0);
  await result.getByRole('button', { name: '关闭' }).click();
  await page.getByRole('button', { name: '查看本次成绩' }).click();
  result = page.getByRole('dialog', { name: '练习成绩' });
  await expect(result.getByText('审核未通过。')).toBeVisible();
  await expect(result.getByText('处理说明：请重新练习后提交')).toBeVisible();
  await expect(result.getByText('内部审核细节')).toHaveCount(0);
  await expect(result.getByRole('button', { name: '提交到排行榜' })).toHaveCount(0);
  await result.getByRole('button', { name: '关闭' }).click();
  await page.getByRole('button', { name: '我的记录' }).click();
  await page.getByRole('button', { name: '《背影》详情' }).click();
  const detail = page.getByRole('dialog', { name: '练习详情' });
  await expect(detail.getByText('审核未通过。')).toBeVisible();
  await expect(detail.getByText('处理说明：请重新练习后提交')).toBeVisible();
  await expect(detail.getByText('内部审核细节')).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('dialog', { name: '练习详情' }).getByText('审核未通过。')).toBeVisible();
  await adminContext.close();
});

test('checks the server after a lost submission response instead of guessing success', async ({ page }) => {
  const username = 'score_lost'; const email = `${username}@example.test`;
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { email, username, password: 'score-password-123', code } })).ok()).toBe(true);
  await page.goto('/');
  await page.getByRole('textbox', { name: '当前行输入' }).fill('我');
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: '结束练习', exact: true }).click();
  await page.getByRole('dialog', { name: '结束本次练习？' }).getByRole('button', { name: '结束并查看成绩' }).click();
  const result = page.getByRole('dialog', { name: '练习成绩' });
  await expect(result.getByText('尚未提交。')).toBeVisible();
  await page.route('**/api/leaderboard', async (route) => { await route.fetch(); await route.abort('failed'); }, { times: 1 });
  await result.getByRole('button', { name: '提交到排行榜' }).click();
  await expect(result.getByText('已提交，待复核。')).toBeVisible();
  await expect(result.getByRole('button', { name: '提交到排行榜' })).toHaveCount(0);
  await expect(result.getByText('已上榜。')).toHaveCount(0);
});
