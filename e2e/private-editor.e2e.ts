import { expect, test } from './fixtures';

test('protects private article edits and keeps the original draft snapshot after deletion', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '新建文章' }).click();
  let editor = page.getByRole('dialog', { name: '新建文章' });
  await editor.getByLabel('标题').fill('私人练习');
  await editor.getByLabel('正文').fill('春山落雨，旧信仍在。');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect(editor).toBeHidden();
  await page.getByRole('button', { name: '练习《私人练习》' }).click();
  await page.getByRole('textbox', { name: '当前行输入' }).fill('春');
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '编辑《私人练习》' }).click();
  editor = page.getByRole('dialog', { name: '编辑文章' });
  await editor.getByLabel('正文').fill('尚未保存的正文');
  await page.keyboard.press('Escape');
  let confirm = page.getByRole('dialog', { name: '放弃未保存的修改？' });
  await expect(confirm).toBeVisible();
  await confirm.getByRole('button', { name: '继续编辑' }).click();
  await expect(editor.getByLabel('正文')).toHaveValue('尚未保存的正文');
  await editor.getByLabel('导入 TXT').setInputFiles({ name: '新文.txt', mimeType: 'text/plain', buffer: Buffer.from('来自文件的新正文') });
  confirm = page.getByRole('dialog', { name: '替换当前正文？' });
  await expect(confirm).toBeVisible();
  await confirm.getByRole('button', { name: '取消' }).click();
  await expect(editor.getByLabel('正文')).toHaveValue('尚未保存的正文');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect(editor).toBeHidden();
  await page.getByRole('button', { name: '删除《私人练习》' }).click();
  const deletion = page.getByRole('dialog', { name: '删除《私人练习》？' });
  await expect(deletion.getByText('已有草稿和历史记录保留原文章快照。')).toBeVisible();
  await deletion.getByRole('button', { name: '删除', exact: true }).click();
  await expect(deletion).toBeHidden();
  await page.getByRole('button', { name: '更多' }).click();
  await page.getByRole('button', { name: '草稿箱' }).click();
  await page.getByRole('button', { name: '继续《私人练习》' }).click();
  await expect(page.getByRole('textbox', { name: '当前行输入' })).toHaveValue('春');
  await expect(page.getByLabel('当前文章：私人练习')).toContainText('春山落雨');
});
