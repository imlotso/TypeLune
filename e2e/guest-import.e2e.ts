import { expect, test } from './fixtures';

test('explicitly imports guest data, can cancel and repeat, and clears only the chosen guest copy', async ({ page }) => {
  test.setTimeout(60_000);
  await page.goto('/');
  await page.getByLabel('测试时间（分钟）').fill('7');
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '收藏《背影》' }).click();
  await page.getByRole('button', { name: '新建文章' }).click();
  await page.getByRole('dialog').waitFor();
  const guestNotice = page.getByRole('dialog', { name: '游客文章仅保存在本机' });
  if (await guestNotice.isVisible()) await guestNotice.getByRole('button', { name: '我已知晓，继续创建' }).click();
  const editor = page.getByRole('dialog', { name: '新建文章' });
  await editor.getByLabel('标题').fill('游客文章');
  await editor.getByLabel('正文').fill('山海相望，故人未归。');
  await editor.getByRole('button', { name: '保存' }).click();
  await page.getByRole('button', { name: '练习《游客文章》' }).click();
  let input = page.getByRole('textbox', { name: '当前行输入' });
  await input.fill('山');
  await page.waitForTimeout(1200);
  await input.fill('山海相望，故人未归。');
  await page.getByRole('dialog', { name: '练习成绩' }).getByRole('button', { name: '再练一次' }).click();
  input = page.getByRole('textbox', { name: '当前行输入' });
  await input.fill('山');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  let auth = page.getByRole('dialog', { name: '登录' });
  await auth.getByRole('button', { name: '创建账号' }).click();
  auth = page.getByRole('dialog', { name: '创建账号' });
  const email = 'guest_import@example.test';
  await auth.getByLabel('用户名', { exact: true }).fill('guest_import');
  await auth.getByLabel('邮箱', { exact: true }).fill(email);
  await auth.getByLabel('密码', { exact: true }).fill('import-password-123');
  const emailSent = page.waitForResponse((response) => response.url().endsWith('/api/auth/code') && response.request().method() === 'POST');
  await auth.getByRole('button', { name: '获取验证码' }).click();
  expect((await emailSent).status()).toBe(200);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  await auth.getByLabel('邮箱验证码', { exact: true }).fill(code);
  await auth.getByRole('button', { name: '注册并登录' }).click();
  await expect(page.getByRole('button', { name: 'guest_import', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '导入游客资料' })).toBeVisible();
  expect((await (await page.request.get('/api/workspace')).json()).items).toEqual([]);
  await page.getByRole('button', { name: '导入游客资料' }).click();
  let dialog = page.getByRole('dialog', { name: '导入游客资料' });
  await expect(dialog.getByText('私人文章：1 项')).toBeVisible();
  await expect(dialog.getByText('草稿：1 项')).toBeVisible();
  await expect(dialog.getByText('记录：1 项')).toBeVisible();
  await dialog.getByRole('button', { name: '取消' }).click();
  expect((await (await page.request.get('/api/workspace')).json()).items).toEqual([]);
  await page.getByRole('button', { name: '导入游客资料' }).click();
  dialog = page.getByRole('dialog', { name: '导入游客资料' });
  await expect(dialog.getByRole('button', { name: '导入游客资料' })).toBeEnabled();
  await dialog.getByRole('button', { name: '导入游客资料' }).click();
  await expect(dialog.getByText(/已同步 \d+ 项/)).toBeVisible();
  const cloud = (await (await page.request.get('/api/workspace')).json()).items as Array<{ kind: string; value?: Record<string, unknown> }>;
  expect(cloud.find((item) => item.kind === 'draft')?.value).toMatchObject({ typed: '山', offline: true, personalOnly: true });
  expect(cloud.find((item) => item.kind === 'draft')?.value).not.toHaveProperty('recoveryKey');
  expect(cloud.find((item) => item.kind === 'record')?.value).toMatchObject({ localOnly: true });
  expect(cloud.find((item) => item.kind === 'settings')?.value).toMatchObject({ minutes: 7 });
  await dialog.getByRole('button', { name: '清除游客副本' }).click();
  await page.getByRole('dialog', { name: '清除游客副本？' }).getByRole('button', { name: '保留' }).click();
  await dialog.getByRole('button', { name: '完成' }).click();
  await page.getByRole('button', { name: 'guest_import', exact: true }).click();
  await page.getByRole('menuitem', { name: '个人数据' }).click();
  await page.getByRole('button', { name: '导入游客资料' }).click();
  dialog = page.getByRole('dialog', { name: '导入游客资料' });
  await dialog.getByRole('button', { name: '导入游客资料' }).click();
  await expect(dialog.getByText(/已同步 \d+ 项/)).toBeVisible();
  expect((await (await page.request.get('/api/workspace')).json()).items).toHaveLength(cloud.length);
  await dialog.getByRole('button', { name: '清除游客副本' }).click();
  await page.getByRole('dialog', { name: '清除游客副本？' }).getByRole('button', { name: '确认清除' }).click();
  await expect(dialog.getByText('游客副本已清除')).toBeVisible();
  await dialog.getByRole('button', { name: '完成' }).click();
  await page.getByRole('button', { name: 'guest_import', exact: true }).click();
  await page.getByRole('menuitem', { name: '退出登录' }).click();
  await page.getByRole('dialog', { name: '退出登录' }).getByRole('button', { name: '确认退出' }).click();
  await page.getByRole('button', { name: '文章库' }).click();
  await expect(page.getByRole('button', { name: '收藏《背影》' })).toHaveAttribute('aria-pressed', 'false');
  await expect(page.getByRole('button', { name: '练习《游客文章》' })).toHaveCount(0);
});

test('retains guest data when cloud synchronization fails and completes on retry', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '收藏《背影》' }).click();
  const email = 'guest_retry@example.test'; const password = 'import-password-123';
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { email, username: 'guest_retry', password, code } })).ok()).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: 'guest_retry', exact: true }).click();
  await page.getByRole('menuitem', { name: '个人数据' }).click();
  await page.getByRole('button', { name: '导入游客资料' }).click();
  const dialog = page.getByRole('dialog', { name: '导入游客资料' });
  await expect(dialog.getByRole('button', { name: '导入游客资料' })).toBeEnabled();
  await page.route('**/api/workspace/sync', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试连接失败' }) }));
  await dialog.getByRole('button', { name: '导入游客资料' }).click();
  await expect(dialog.getByRole('alert')).toContainText('尚未全部同步');
  await expect(dialog.getByRole('button', { name: '清除游客副本' })).toHaveCount(0);
  await page.unroute('**/api/workspace/sync');
  await dialog.getByRole('button', { name: '立即同步' }).click();
  await expect(dialog.getByRole('button', { name: '重试导入和同步' })).toBeEnabled();
  await dialog.getByRole('button', { name: '重试导入和同步' }).click();
  await expect(dialog.getByText('已同步 1 项。')).toBeVisible();
  expect((await (await page.request.get('/api/workspace')).json()).items.some((item: { id: string; deleted?: boolean }) => item.id === 'zh-beginner-1' && !item.deleted)).toBe(true);
  await dialog.getByRole('button', { name: '完成' }).click();
  await page.getByRole('button', { name: 'guest_retry', exact: true }).click();
  await page.getByRole('menuitem', { name: '退出登录' }).click();
  await page.getByRole('dialog', { name: '退出登录' }).getByRole('button', { name: '确认退出' }).click();
  await page.getByRole('button', { name: '文章库' }).click();
  await expect(page.getByRole('button', { name: '收藏《背影》' })).toHaveAttribute('aria-pressed', 'true');
});
