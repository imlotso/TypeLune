import { test, expect, ensureAdmin } from './fixtures';
import QRCode from 'qrcode';
import sharp from 'sharp';
import jsQR from 'jsqr';
import { mkdirSync } from 'node:fs';

test('administrator publishes real sanitized test QR images to the quiet footer and can remove them', async ({ page, browser }) => {
  test.setTimeout(60_000);
  const shots='docs/qa/screenshots/2026-11-16-lessons';mkdirSync(shots,{recursive:true});
  await page.setViewportSize({width:1440,height:1000});
  await ensureAdmin(page.request);
  await page.goto('/admin');
  await page.getByRole('button',{name:'捐赠设置',exact:true}).click();
  await expect(page.getByLabel('显示捐赠入口')).not.toBeChecked();
  const payload='TypeLune test fixture - NOT A PAYMENT';
  const png=await QRCode.toBuffer(payload,{width:384,margin:4,errorCorrectionLevel:'M'});
  const label=Buffer.from('<svg width="384" height="46"><rect width="384" height="46" fill="white"/><text x="192" y="27" text-anchor="middle" font-family="Arial" font-size="16" fill="#333">TEST ONLY - NOT A PAYMENT</text></svg>');
  const fixture=await sharp(png).extend({bottom:46,background:'#fff'}).composite([{input:label,left:0,top:384}]).png().toBuffer();
  await page.getByLabel('支付宝收款码',{exact:true}).setInputFiles({name:'test-alipay.png',mimeType:'image/png',buffer:fixture});
  await page.getByLabel('微信收款码',{exact:true}).setInputFiles({name:'test-wechat.png',mimeType:'image/png',buffer:fixture});
  await page.getByLabel('显示捐赠入口').check();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await expect(page.getByText('已保存',{exact:true})).toBeVisible();
  await page.screenshot({path:shots+'/desktop-admin-support-test-fixtures.png',fullPage:true});
  const exposed=await(await page.request.get('/api/site/support')).json();
  expect(Object.keys(exposed).sort()).toEqual(['alipay','enabled','wechat']);
  const {data,info}=await sharp(Buffer.from(exposed.alipay.dataUrl.split(',')[1],'base64')).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  expect(jsQR(new Uint8ClampedArray(data),info.width,info.height)?.data).toBe(payload);
  await page.getByLabel('显示捐赠入口').uncheck();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'概览',exact:true}).click();
  await expect(page.getByLabel('显示捐赠入口')).toBeVisible();
  await page.getByLabel('显示捐赠入口').check();

  const guest=await browser.newContext({locale:'zh-CN',viewport:{width:1440,height:1000}});
  const front=await guest.newPage();
  await front.goto('/lessons');
  const support=front.getByRole('button',{name:'支持 TypeLune',exact:true});
  await expect(support).toHaveClass(/text-button/);
  expect(await support.getAttribute('class')).not.toContain('primary');
  await support.click();
  await expect(front.getByRole('img',{name:'支付宝收款码',exact:true})).toBeVisible();
  await expect(front.getByRole('img',{name:'微信收款码',exact:true})).toBeVisible();
  await front.screenshot({path:shots+'/desktop-support-dialog-test-fixtures.png',fullPage:false});
  await front.keyboard.press('Escape');await expect(front.getByRole('dialog')).toHaveCount(0);
  await expect(support).toBeFocused();
  await front.setViewportSize({width:390,height:844});
  await front.getByRole('button',{name:'界面语言：中文，切换为 English'}).click();
  await front.getByRole('button',{name:'Switch to dark mode',exact:true}).click();
  await front.getByRole('button',{name:'Support TypeLune',exact:true}).click();
  await expect(front.getByRole('img',{name:'WeChat payment QR code'})).toBeVisible();
  expect(await front.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await front.screenshot({path:shots+'/mobile-support-dialog-test-fixtures-en.png',fullPage:false});
  const rejected=await front.request.post('/api/admin/support',{data:{settings:exposed,revision:1}});
  expect([401,403]).toContain(rejected.status());

  await page.getByRole('button',{name:'移除',exact:true}).first().click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await expect(page.getByText('已保存',{exact:true})).toBeVisible();
  await front.keyboard.press('Escape');
  await front.getByRole('button',{name:'Support TypeLune',exact:true}).click();
  await expect(front.getByRole('img',{name:'Alipay payment QR code'})).toHaveCount(0);
  await expect(front.getByRole('img',{name:'WeChat payment QR code'})).toBeVisible();
  await page.getByLabel('显示捐赠入口').uncheck();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await expect(page.getByText('已保存',{exact:true})).toBeVisible();
  await front.reload();
  await expect(front.getByRole('button',{name:'Support TypeLune',exact:true})).toHaveCount(0);
  await guest.close();
});
