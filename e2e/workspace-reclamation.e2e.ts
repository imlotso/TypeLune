import { readFile } from 'node:fs/promises';
import { expect, test } from './fixtures';

test('keeps an offline device from reviving deleted data and offers an export after reclamation', async ({ page, browser, clientIp }) => {
  test.setTimeout(90_000);
  const email = 'reclamation@example.test'; const username = 'reclamation'; const password = 'reclaim-password-123';
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { email, username, password, code } })).ok()).toBe(true);
  await page.goto('/');
  await page.getByRole('button', { name: '文章库' }).click();
  await page.getByRole('button', { name: '收藏《背影》' }).click();
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).items.some((item: { id: string; deleted?: boolean }) => item.id === 'zh-beginner-1' && !item.deleted)).toBe(true);

  const device = await browser.newContext({ baseURL: test.info().project.use.baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  expect((await device.request.post('/api/auth/login', { data: { identifier: username, password } })).ok()).toBe(true);
  const other = await device.newPage();
  await other.goto('/');
  await other.getByRole('button', { name: '文章库' }).click();
  await expect(other.getByRole('button', { name: '收藏《背影》' })).toHaveAttribute('aria-pressed', 'true');
  await device.setOffline(true);
  await page.getByRole('button', { name: '收藏《背影》' }).click();
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).items.some((item: { id: string; deleted?: boolean }) => item.id === 'zh-beginner-1' && item.deleted)).toBe(true);
  await other.getByRole('button', { name: '收藏《荷塘月色》' }).click();
  await device.setOffline(false);
  await other.getByRole('button', { name: '更多' }).click();
  await other.getByRole('button', { name: '设置', exact: true }).click();
  const settings = other.getByRole('dialog', { name: '练习设置' });
  await settings.getByRole('button', { name: '立即同步' }).click();
  await expect(settings.getByText('已同步')).toBeVisible();
  await settings.getByRole('button', { name: '关闭' }).click();
  await expect(other.getByRole('button', { name: '收藏《背影》' })).toHaveAttribute('aria-pressed', 'false');
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).items.some((item: { id: string; deleted?: boolean }) => item.id === 'zh-beginner-2' && !item.deleted)).toBe(true);

  await device.setOffline(true);
  await other.getByRole('button', { name: '收藏《从百草园到三味书屋》' }).click();
  await expect(other.getByRole('button', { name: '收藏《从百草园到三味书屋》' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: username, exact: true }).click();
  await page.getByRole('menuitem', { name: '个人数据' }).click();
  await page.getByRole('button', { name: '整理删除标记' }).click();
  await page.getByRole('button', { name: '确认整理' }).click();
  await expect(page.getByRole('dialog', { name: '处理同步冲突' })).toBeVisible();
  await device.setOffline(false);
  await other.getByRole('button', { name: '更多' }).click();
  await other.getByRole('button', { name: '设置', exact: true }).click();
  await settings.getByRole('button', { name: '立即同步' }).click();
  const recovery = other.getByRole('dialog', { name: '处理同步冲突' });
  if (!await recovery.isVisible()) await settings.getByRole('button', { name: '处理同步冲突' }).click();
  const download = other.waitForEvent('download');
  await recovery.getByRole('button', { name: '导出本机资料' }).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.data.favorites).toContainEqual({ articleId: 'zh-beginner-3' });
  await recovery.getByRole('checkbox', { name: '我已备份或确认放弃本机未同步资料' }).check();
  await recovery.getByRole('button', { name: '重新同步' }).click();
  await expect(recovery).toBeHidden();
  const cloud = (await (await page.request.get('/api/workspace')).json()).items as Array<{ id: string }>;
  expect(cloud.some((item) => item.id === 'zh-beginner-1' || item.id === 'zh-beginner-3')).toBe(false);
  expect(cloud.some((item) => item.id === 'zh-beginner-2')).toBe(true);
  await device.close();
});
