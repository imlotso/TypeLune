import { expect, test } from './fixtures';

test('updates account identity and signs out all sessions after a password change', async ({ page, browser, clientIp }) => {
  const username = 'account_e2e';
  const email = 'account_e2e@example.test';
  const password = 'original-password-123';
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { username, email, password, code } })).ok()).toBe(true);
  const other = await browser.newContext({ baseURL: test.info().project.use.baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  expect((await other.request.post('/api/auth/login', { data: { identifier: username, password } })).ok()).toBe(true);
  await page.goto('/');
  const trigger = page.getByRole('button', { name: username, exact: true });
  await trigger.click();
  await expect(page.getByRole('menuitem', { name: '账号设置' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await trigger.click();
  await page.getByRole('menuitem', { name: '账号设置' }).click();
  const dialog = page.getByRole('dialog', { name: '账号设置' });
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.locator('summary').filter({ hasText: '修改密码' })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(dialog.getByRole('button', { name: '关闭' })).toBeFocused();
  await dialog.locator('summary').filter({ hasText: '更改用户名' }).click();
  await dialog.getByLabel('用户名', { exact: true }).fill('account_renamed');
  await dialog.getByLabel('当前密码（用户名）', { exact: true }).fill(password);
  await dialog.getByRole('button', { name: '显示当前密码（用户名）' }).click();
  await dialog.locator('summary').filter({ hasText: '更改用户名' }).click();
  await dialog.locator('summary').filter({ hasText: '更改用户名' }).click();
  await expect(dialog.getByLabel('当前密码（用户名）', { exact: true })).toHaveAttribute('type', 'password');
  await expect(dialog.getByLabel('当前密码（用户名）', { exact: true })).toHaveValue(password);
  await dialog.getByRole('button', { name: '保存用户名' }).click();
  await expect(dialog.getByText('用户名已保存')).toBeVisible();
  await expect(page.getByRole('button', { name: username, exact: true })).toBeVisible();
  await dialog.getByLabel('公开昵称').fill('小星');
  await dialog.getByLabel('头像').selectOption('star');
  await dialog.getByRole('button', { name: '保存资料' }).click();
  await expect(dialog.getByText('资料已保存')).toBeVisible();
  await dialog.getByRole('button', { name: '关闭' }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: '小星', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '小星', exact: true }).click();
  await page.getByRole('menuitem', { name: '账号设置' }).click();
  await dialog.locator('summary').filter({ hasText: '更改用户名' }).click();
  await expect(dialog.getByLabel('用户名', { exact: true })).toHaveValue('account_renamed');
  await expect(dialog.getByLabel('头像')).toHaveValue('star');
  await dialog.locator('summary').filter({ hasText: '修改密码' }).click();
  await dialog.getByLabel('当前密码', { exact: true }).fill(password);
  await dialog.getByLabel('新密码', { exact: true }).fill('changed-password-456');
  await dialog.getByLabel('确认新密码', { exact: true }).fill('changed-password-456');
  await dialog.getByRole('button', { name: '修改密码' }).click();
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeVisible();
  expect((await (await other.request.get('/api/me')).json()).user).toBeNull();
  expect((await page.request.post('/api/auth/login', { data: { identifier: email, password: 'changed-password-456' } })).ok()).toBe(true);
  await other.close();
});

test('verifies a replacement email before changing login and revokes another session', async ({ page, browser, clientIp }) => {
  const email = 'email_change@example.test';
  const target = 'email_new@example.test';
  const password = 'original-password-123';
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { username: 'email_change', email, password, code } })).ok()).toBe(true);
  const other = await browser.newContext({ baseURL: test.info().project.use.baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  expect((await other.request.post('/api/auth/login', { data: { identifier: email, password } })).ok()).toBe(true);
  await page.goto('/');
  await page.getByRole('button', { name: 'email_change', exact: true }).click();
  await page.getByRole('menuitem', { name: '账号设置' }).click();
  const dialog = page.getByRole('dialog', { name: '账号设置' });
  await dialog.locator('summary').filter({ hasText: '更换邮箱' }).click();
  await dialog.getByLabel('新邮箱', { exact: true }).fill(target);
  await dialog.getByLabel('当前密码（邮箱）', { exact: true }).fill(password);
  await dialog.getByRole('button', { name: '获取邮箱验证码' }).click();
  await expect(dialog.getByText('验证码请求已提交')).toBeVisible();
  await expect(dialog.getByRole('button', { name: /秒后重发/ })).toBeDisabled();
  expect((await (await other.request.get('/api/me')).json()).user.email).toBe(email);
  const nextCode = (await (await page.request.get(`/__e2e__/email-code?email=${target}&purpose=change-email`)).json()).code;
  await dialog.getByLabel('新邮箱验证码', { exact: true }).fill(nextCode);
  await dialog.getByRole('button', { name: '验证并更换邮箱' }).click();
  await expect(page.getByText('邮箱已更新，请重新登录')).toBeVisible();
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeVisible();
  expect((await (await other.request.get('/api/me')).json()).user).toBeNull();
  expect((await page.request.post('/api/auth/login', { data: { identifier: email, password } })).status()).toBe(401);
  expect((await page.request.post('/api/auth/login', { data: { identifier: target, password } })).ok()).toBe(true);
  expect((await page.request.post('/api/auth/code', { data: { email: target, purpose: 'reset' } })).ok()).toBe(true);
  expect((await page.request.get(`/__e2e__/email-code?email=${target}&purpose=reset`)).status()).toBe(200);
  await other.close();
});
