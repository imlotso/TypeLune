test('shows daily activity and opens a record from the selected date', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '自定义文字' }).click();
  const editor = page.getByRole('dialog', { name: '自定义练习文字' });
  await editor.getByRole('textbox', { name: '自定义文章内容' }).fill('山海');
  await editor.getByRole('button', { name: '使用这段文字' }).click();
  await page.getByRole('textbox', { name: '当前行输入' }).fill('山海');
  await page.getByRole('dialog', { name: '练习成绩' }).getByRole('button', { name: '关闭' }).click();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('button', { name: '自定义文字' }).click();
  await editor.getByRole('textbox', { name: '自定义文章内容' }).fill('cloud');
  await editor.getByRole('button', { name: '使用这段文字' }).click();
  await page.getByRole('textbox', { name: '当前行输入' }).fill('cloud');
  await page.getByRole('dialog', { name: '练习成绩' }).getByRole('button', { name: '关闭' }).click();
  await page.getByRole('button', { name: '更多' }).click();
  await page.getByRole('button', { name: '统计', exact: true }).click();
  const calendar = page.getByRole('region', { name: '活动日历' });
  const today = await page.evaluate(() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; });
  await expect(calendar.getByRole('button', { name: `${today}，2 次` })).toBeVisible();
  await expect(calendar.getByText('本机最长')).toBeVisible();
  await calendar.getByText('日历设置', { exact: true }).click();
  await calendar.getByLabel('每日目标（分钟，0 为关闭）').fill('5');
  await calendar.getByRole('button', { name: '保存日历设置' }).click();
  await expect(calendar.getByText('已保存在本机')).toBeVisible();
  await page.reload();
  await calendar.getByText('日历设置', { exact: true }).click();
  await expect(calendar.getByLabel('每日目标（分钟，0 为关闭）')).toHaveValue('5');
  await calendar.getByRole('button', { name: `${today}，2 次` }).click();
  await calendar.getByRole('list', { name: '当日记录' }).getByRole('button', { name: /查看记录/ }).first().click();
  await expect(page).toHaveURL(/\/records\/[^/]+$/);
  await expect(page.getByRole('dialog', { name: '练习详情' })).toBeVisible();
});

test('synchronizes account time zone and daily goal across devices and exports them', async ({ page, browser, baseURL, clientIp }) => {
  const username = 'calendar_member'; const email = `${username}@example.test`; const password = 'calendar-password-123';
  expect((await page.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await page.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await page.request.post('/api/auth/register', { data: { username, email, password, code } })).ok()).toBe(true);
  await page.goto('/stats');
  const calendar = page.getByRole('region', { name: '活动日历' });
  await calendar.getByText('日历设置', { exact: true }).click();
  await calendar.getByLabel('统计时区').fill('Asia/Tokyo');
  await calendar.getByLabel('每日目标（分钟，0 为关闭）').fill('20');
  await calendar.getByRole('button', { name: '保存日历设置' }).click();
  await expect(calendar.getByText('已保存在本机')).toBeVisible();
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).items.some((item: { kind: string; value?: { statisticsTimezone?: string; dailyGoalMinutes?: number } }) => item.kind === 'settings' && item.value?.statisticsTimezone === 'Asia/Tokyo' && item.value?.dailyGoalMinutes === 20)).toBe(true);
  const other = await browser.newContext({ baseURL, timezoneId: 'America/Los_Angeles', extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  expect((await other.request.post('/api/auth/login', { data: { identifier: username, password } })).ok()).toBe(true);
  const reader = await other.newPage(); await reader.goto('/stats');
  const otherCalendar = reader.getByRole('region', { name: '活动日历' });
  await otherCalendar.getByText('日历设置', { exact: true }).click();
  await expect(otherCalendar.getByLabel('统计时区')).toHaveValue('Asia/Tokyo');
  await expect(otherCalendar.getByLabel('每日目标（分钟，0 为关闭）')).toHaveValue('20');
  await otherCalendar.getByLabel('统计时区').fill('UTC');
  await otherCalendar.getByLabel('每日目标（分钟，0 为关闭）').fill('30');
  await otherCalendar.getByRole('button', { name: '保存日历设置' }).click();
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).items.some((item: { kind: string; value?: { statisticsTimezone?: string; dailyGoalMinutes?: number } }) => item.kind === 'settings' && item.value?.statisticsTimezone === 'UTC' && item.value?.dailyGoalMinutes === 30)).toBe(true);
  await page.getByRole('button', { name: '更多' }).click();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '练习设置' });
  await settings.getByRole('button', { name: '立即同步' }).click();
  await expect(settings.getByText('已同步')).toBeVisible();
  await settings.getByRole('button', { name: '关闭' }).click();
  await expect(calendar.getByLabel('统计时区')).toHaveValue('UTC');
  await expect(calendar.getByLabel('每日目标（分钟，0 为关闭）')).toHaveValue('30');
  await page.getByRole('button', { name: username, exact: true }).click();
  await page.getByRole('menuitem', { name: '个人数据' }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出个人数据 JSON' }).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.data.settings).toMatchObject({ statisticsTimezone: 'UTC', dailyGoalMinutes: 30 });
  await other.close();
});
