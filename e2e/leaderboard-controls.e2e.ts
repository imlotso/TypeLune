import { ensureAdmin, expect, test } from './fixtures';

test('keeps board filters across browsers and lets an administrator review and clear a date range', async ({ page, browser, baseURL, clientIp }, testInfo) => {
  test.setTimeout(90_000);
  await page.goto('/');
  await page.getByRole('textbox', { name: '当前行输入' }).fill('我');
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: '结束练习', exact: true }).click();
  await page.getByRole('dialog', { name: '结束本次练习？' }).getByRole('button', { name: '结束并查看成绩' }).click();
  const result = page.getByRole('dialog', { name: '练习成绩' });
  const nickname = result.getByLabel('上榜昵称');
  await expect(nickname).toHaveValue('visitor');
  await nickname.fill('云朵');
  await expect(result.getByRole('button', { name: '提交到排行榜' })).toBeDisabled();
  await expect(result.getByText(/游客昵称须以 visitor 开头/)).toBeVisible();
  await nickname.fill('visitor-浏览器');
  await result.getByRole('button', { name: '提交到排行榜' }).click();
  await expect(result.getByText('已提交，待复核。')).toBeVisible();
  await result.getByRole('button', { name: '排行榜', exact: true }).click();
  await expect(page.getByRole('button', { name: '游客榜', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('排行时段').selectOption('week');
  await expect(page).toHaveURL(/board=guest/);
  await expect(page).toHaveURL(/period=week/);

  const otherContext = await browser.newContext({ baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  const shared = new URL(page.url()); shared.pathname += '/';
  const other = await otherContext.newPage(); await other.goto(shared.toString());
  await expect(other.getByRole('button', { name: '游客榜', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(other.getByLabel('排行时段')).toHaveValue('week');
  await expect(other.getByText('visitor-浏览器')).toHaveCount(0);

  const adminContext = await browser.newContext({ baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  await ensureAdmin(adminContext.request);
  const admin = await adminContext.newPage(); await admin.goto('/admin');
  await admin.getByRole('button', { name: '成绩', exact: true }).click();
  const guestRow = admin.locator('li').filter({ hasText: 'visitor-浏览器' });
  await expect(guestRow.getByText('游客成绩默认审核')).toBeVisible();
  await guestRow.getByRole('button', { name: '通过', exact: true }).click();
  const approve = admin.getByRole('dialog', { name: '通过成绩' });
  await approve.getByLabel('原因', { exact: true }).fill('核对通过');
  await approve.getByRole('button', { name: '确认通过' }).click();
  await expect(approve).toHaveCount(0);
  await other.reload();
  const ranked = other.locator('.ranking-list li').filter({ hasText: 'visitor-浏览器' });
  await expect(ranked).toBeVisible();
  await expect(ranked.locator('time')).toBeVisible();
  await other.getByRole('button', { name: '用户榜', exact: true }).click();
  await expect(other.getByText('visitor-浏览器')).toHaveCount(0);
  await other.getByRole('button', { name: '游客榜', exact: true }).click();
  await expect(ranked).toBeVisible();
  await other.screenshot({ path: testInfo.outputPath('typeflow-ranking-desktop-light.png') });
  await other.setViewportSize({ width: 390, height: 844 });
  await other.getByRole('button', { name: '切换至夜间模式' }).click();
  await expect(other.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await other.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await other.screenshot({ path: testInfo.outputPath('typeflow-ranking-mobile-dark.png') });

  const readerContext = await browser.newContext({ baseURL, extraHTTPHeaders: { 'X-Forwarded-For': clientIp } });
  const email = 'ranking_reader@example.test';
  expect((await readerContext.request.post('/api/auth/code', { data: { email, purpose: 'register' } })).ok()).toBe(true);
  const code = (await (await readerContext.request.get(`/__e2e__/email-code?email=${email}&purpose=register`)).json()).code;
  expect((await readerContext.request.post('/api/auth/register', { data: { username: 'ranking_reader', email, password: 'ranking-password-123', code } })).ok()).toBe(true);
  const reader = await readerContext.newPage(); await reader.goto('/');
  await reader.getByRole('textbox', { name: '当前行输入' }).fill('我');
  await reader.waitForTimeout(1200);
  await reader.getByRole('button', { name: '结束练习', exact: true }).click();
  await reader.getByRole('dialog', { name: '结束本次练习？' }).getByRole('button', { name: '结束并查看成绩' }).click();
  const readerResult = reader.getByRole('dialog', { name: '练习成绩' });
  await readerResult.getByRole('button', { name: '提交到排行榜' }).click();
  await expect(readerResult.getByText('已提交，待复核。')).toBeVisible();
  await admin.getByRole('button', { name: '概览', exact: true }).click();
  await admin.getByRole('button', { name: '成绩', exact: true }).click();
  const pendingUser = admin.locator('li').filter({ hasText: 'ranking_reader' });
  await pendingUser.getByRole('button', { name: '通过', exact: true }).click();
  const approveUser = admin.getByRole('dialog', { name: '通过成绩' });
  await approveUser.getByLabel('原因', { exact: true }).fill('核对通过');
  await approveUser.getByRole('button', { name: '确认通过' }).click();
  await expect(approveUser).toHaveCount(0);
  await other.getByRole('button', { name: '用户榜', exact: true }).click();
  await expect(other.getByText('ranking_reader')).toBeVisible();
  await expect(other.getByText('visitor-浏览器')).toHaveCount(0);
  await other.getByRole('button', { name: '游客榜', exact: true }).click();
  await expect(ranked).toBeVisible();
  await admin.getByLabel('成绩状态').selectOption('published');
  await admin.getByLabel('榜单类型').selectOption('user');
  const publishedUser = admin.locator('li').filter({ hasText: 'ranking_reader' });
  await publishedUser.getByRole('button', { name: '拒绝', exact: true }).click();
  const reject = admin.getByRole('dialog', { name: '拒绝成绩' });
  await reject.getByLabel('原因', { exact: true }).fill('重新核对');
  await reject.getByLabel('用户可见说明').fill('请重新练习');
  await reject.getByRole('button', { name: '确认拒绝' }).click();
  await expect(reject).toHaveCount(0);
  await readerResult.getByRole('button', { name: '关闭' }).click();
  await reader.getByRole('button', { name: '查看本次成绩' }).click();
  await expect(reader.getByRole('dialog', { name: '练习成绩' }).getByText('审核未通过。')).toBeVisible();

  await admin.getByLabel('榜单类型').selectOption('guest');
  const now = new Date();
  const date = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  await admin.getByLabel('开始日期').fill(date);
  await admin.getByLabel('结束日期').fill(date);
  await admin.getByRole('button', { name: '筛选日期' }).click();
  await expect(admin.locator('li').filter({ hasText: 'visitor-浏览器' })).toBeVisible();
  await admin.getByRole('button', { name: '清理筛选范围内的排行榜' }).click();
  const cleanup = admin.getByRole('dialog', { name: '按日期清理排行榜' });
  await expect(cleanup.getByText(/保留个人练习历史/)).toBeVisible();
  await admin.screenshot({ path: testInfo.outputPath('typeflow-ranking-cleanup-desktop.png') });
  await cleanup.getByLabel('原因', { exact: true }).fill('测试日期清理');
  await cleanup.getByRole('button', { name: '确认清理' }).click();
  await expect(cleanup).toHaveCount(0);
  await other.reload();
  await expect(other.getByText('visitor-浏览器')).toHaveCount(0);
  await expect(other.getByLabel('排行时段')).toHaveValue('week');
  await otherContext.close(); await adminContext.close(); await readerContext.close();
});
